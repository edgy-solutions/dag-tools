"""The measurement grammar, rendered as SQL from the same rule table.

Two routes read one table. :mod:`dag_tools.systemlink.measurements` evaluates
it in Python, which is how the grammar is provable with no warehouse; this
module renders it into the dbt models that run it where the data is. The
patterns, the rule order, which rule may read a value and even which columns
the extraction CTE has all come off ``measurements.RULES`` -- written down
once -- because a generator holding its own copy of the grammar is one that
can agree with its tests and disagree with the models.

The shipped SQL in ``dag_tools/dbt_packages/mfg_trace_curated/models`` is this
module's output, compared byte for byte by the package's tests. That
comparison alone would pass on a generator whose SQL is wrong in the same way
as its template, so the same rendering is also executed against the Python
route over one case list. Both tests are needed; neither replaces the other.

Pure: stdlib only, no dbt, no Dagster, no database driver.

Dialect, and what this module refuses to decide
-----------------------------------------------
This library owns no dialect (``contract_mapping``'s ``cast_templates`` take
the same stance), so what differs between warehouses is named by the
deployment and not here:

* regular-expression extraction goes through the package's own
  ``mfg_trace_re_extract`` macro, which dispatches per adapter;
* the decimal type a tolerance is computed in is a required dbt var. A
  tolerance through a binary float is how a limit stops reconciling -- the
  same finding as ``contract_mapping``'s ``factor`` -- so the arithmetic is
  exact and the *type* that makes it exact is the operator's word;
* the comparator table is the deployment's, and this module renders **no
  codes of its own**: a code compiled in here would make a vocabulary
  decision a library release;
* the relations the conformed stage produced are required vars too: this
  package cannot know what a deployment called its own models, and a default
  would read some other deployment's table.
"""
from __future__ import annotations

import pathlib
import re
from typing import Callable, Dict, Iterator, Tuple

from .measurements import RULES, Rule

#: A renderer for "extract capture group ``index`` of ``pattern`` from
#: ``expr``". The generated models call the package's macro; a test that
#: executes the SQL supplies its engine's own function.
ExtractRenderer = Callable[[str, str, int], str]

#: dbt vars the package requires and never defaults. A default here would
#: name a relation belonging to whichever deployment wrote it, pick a numeric
#: type on a warehouse nobody asked about, or -- worst -- invent comparator
#: codes.
REQUIRED_VARS: Tuple[str, ...] = (
    "mfg_trace_conf_result_relation",
    "mfg_trace_conf_step_parameter_relation",
    "mfg_trace_decimal_type",
    "mfg_trace_comparators",
)

GENERATED_HEADER = (
    "-- Generated by dag_tools.systemlink.sql from the rule table in\n"
    "-- dag_tools.systemlink.measurements. Do not edit by hand: a test\n"
    "-- compares the generator's output against this file byte for byte.\n"
)

#: The two texts the grammar reads, and the prefix each one's extracted
#: columns carry.
MEASUREMENT = "measurement"
LIMITS = "limits"

_SOURCE_TEXT = {
    MEASUREMENT: "trim(coalesce(measurement_text, ''))",
    LIMITS: "trim(coalesce(limits_text, ''))",
}

_NAMED_GROUP = re.compile(r"\(\?P<[^>]+>")


def sql_pattern(rule: Rule) -> str:
    """``rule.pattern`` in a form a SQL engine's regex accepts.

    Python's named groups are stripped, because POSIX-flavoured engines
    reject ``(?P<name>...)`` outright. Stripping a name renumbers nothing, so
    :func:`group_index` still answers for the same group.
    """
    return _NAMED_GROUP.sub("(", rule.pattern)


def group_index(rule: Rule, name: str) -> int:
    """The 1-based capture-group number of a named group.

    Read off the compiled pattern rather than counted here, so the number
    cannot drift from the pattern it indexes.
    """
    return rule.regex.groupindex[name]


def group_names(rule: Rule) -> Tuple[str, ...]:
    """A rule's named groups, in the order the pattern declares them."""
    return tuple(
        name
        for name, _ in sorted(rule.regex.groupindex.items(), key=lambda kv: kv[1])
    )


def extracted_columns(
    sources: Tuple[str, ...] = (MEASUREMENT, LIMITS),
) -> Iterator[Tuple[str, str, Rule, str]]:
    """Every (column, source, rule, group) the extraction CTE carries.

    Enumerated from the rule table rather than hand-picked, so a rule added
    to the grammar arrives with its columns instead of needing a second edit
    here that someone has to remember.
    """
    for source in sources:
        for rule in RULES:
            for name in group_names(rule):
                yield "{0}_{1}_{2}".format(source, rule.id, name), source, rule, name


def column_for(source: str, rule_id: str, group: str) -> str:
    """The extraction CTE's column for one group of one rule."""
    return "{0}_{1}_{2}".format(source, rule_id, group)


def quote(text: str) -> str:
    """A SQL string literal. The patterns carry no quote; a guard, not a fix."""
    return "'" + text.replace("'", "''") + "'"


def jinja_string(text: str) -> str:
    """A Jinja string literal carrying SQL text.

    Double-quoted because the SQL it carries contains single quotes, and
    doubled quotes inside in case it ever stops doing so.

    Both of a macro call's arguments have to be literals: Jinja evaluates
    what is inside `{{ ... }}` as an *expression*, so a bare SQL fragment
    there is read as a call to a Jinja function of that name and the parse
    fails -- measured, `UndefinedError: 'coalesce' is undefined`. The macro
    interpolates the string back out as SQL.
    """
    return '"{0}"'.format(text.replace("\\", "\\\\").replace('"', '\\"'))


def macro_extract(expr: str, pattern: str, index: int) -> str:
    """Render through the package's adapter-dispatching macro."""
    return "{{{{ mfg_trace_re_extract({0}, {1}, {2}) }}}}".format(
        jinja_string(expr), jinja_string(pattern), index
    )


def duckdb_extract(expr: str, pattern: str, index: int) -> str:
    """Render for the engine the cross-route test executes on."""
    return "regexp_extract({0}, {1}, {2})".format(expr, quote(pattern), index)


def indent_block(text: str, prefix: str) -> str:
    """Indent every line but the first, so a block embeds at a call site.

    The builders below emit at zero indent and are re-indented here. Having
    each one bake in the indent of its one call site is how generated SQL
    comes out with a `case` under one column and its `end` under another --
    unreadable, and therefore unreviewed.
    """
    lines = text.split("\n")
    return "\n".join(
        [lines[0]] + [prefix + line if line else line for line in lines[1:]]
    )


def _matched(source: str, rule: Rule) -> str:
    """Whether a rule matched its text at all.

    A non-empty *required* group is the match. The group asked is the first
    one the pattern declares, which no match can omit -- never an optional
    one such as the unit, which a matching text may leave out.

    Wrapped in `coalesce` because the engines disagree about what a group
    that did not participate is: some answer an empty string and some answer
    NULL. Unguarded, the NULL convention makes every arm of the CASE
    not-true, so the whole grammar silently falls through to its else -- a
    model that parses nothing at all, on one warehouse only.
    """
    return "coalesce({0}, '') <> ''".format(
        column_for(source, rule.id, group_names(rule)[0])
    )


def _blank_to_null(expr: str) -> str:
    return "nullif(trim({0}), '')".format(expr)


def _case(arms, otherwise: str) -> str:
    """A CASE expression at zero indent, for :func:`indent_block` to place."""
    return "case\n" + "\n".join(arms) + "\n    else " + otherwise + "\nend"


def _double(expr: str) -> str:
    """Parse numeric text as a float, or answer null where it is not one.

    The patterns admit no `inf` and no `nan` literal, so the obvious reading
    is that a plain cast is safe here. It is not, and this docstring used to
    say it was: `1e999` IS finite decimal notation that the number rule
    matches, and casting it answers positive infinity -- measured on the one
    engine anything here is executed on. The Python route answers *absent*
    for the same text, so an unguarded cast is both a divergence between the
    two routes and a non-finite value in a column the contract says holds a
    number, which every numeric path in this repo refuses.

    The guard is `x * 0 = 0`: true of every finite double including zero,
    false of both infinities (infinity times zero is not a number) and false
    of a not-a-number (which compares equal to nothing). It names no magic
    constant and asks for no engine's own finiteness function.

    The limit of it, stated: an engine that *raises* on the cast instead of
    answering infinity -- postgres does, and so does every decimal cast in
    the tolerance arms -- fails the build, and no expression here can catch
    that. A loud failure is the acceptable half of this. A published
    infinity is not.
    """
    cast = "cast({0} as double)".format(expr)
    return "case when {0} * 0 = 0 then {0} else cast(null as double) end".format(cast)


def extraction_select(
    extract: ExtractRenderer,
    indent: str = "        ",
    sources: Tuple[str, ...] = (MEASUREMENT, LIMITS),
) -> str:
    """The extraction CTE's projection: every group of every rule, once.

    Extracting each pattern once and reading columns afterwards is not only
    cheaper at the warehouse; it is what keeps the generated SQL short enough
    that a reviewer will actually read it.
    """
    lines = []
    for column, source, rule, group in extracted_columns(sources):
        lines.append(
            "{indent}{expr} as {column}".format(
                indent=indent,
                expr=extract(
                    _SOURCE_TEXT[source], sql_pattern(rule), group_index(rule, group)
                ),
                column=column,
            )
        )
    # No trailing comma: this is the last thing in its select list, and one
    # there is a syntax error rather than a cosmetic slip.
    return ",\n".join(lines)


def units_expression(source: str) -> str:
    """The unit suffix of whichever rule matched this text, or null.

    A parsed suffix is a **fallback** for the source's own ``units`` column,
    never a column of its own: the curated contract declares no parsed-unit
    column, and adding one would put a column in the model the contract does
    not declare. Getting the direction backwards silently relabels every row
    whose column and suffix disagree.
    """
    arms = [
        "    when {matched} then {unit}".format(
            matched=_matched(source, rule),
            unit=_blank_to_null(column_for(source, rule.id, "unit")),
        )
        for rule in RULES
        if "unit" in rule.regex.groupindex
    ]
    return _case(arms, "cast(null as varchar)")


def operator_expression() -> str:
    """The operator text a limits text states, or null.

    Read only where the *comparator* rule is the one that matched. A
    tolerance is not a comparator, and the rule order is what says so: the
    tolerance rule precedes the comparator rule in the table, so a tolerance
    text is never read as a bound.
    """
    arms = []
    for rule in RULES:
        if rule.kind == "comparator":
            arms.append(
                "    when {0} then {1}".format(
                    _matched(LIMITS, rule),
                    _blank_to_null(column_for(LIMITS, rule.id, "op")),
                )
            )
        else:
            # An arm per rule even where the answer is null, because the arms
            # in order ARE the rule order: a tolerance text reaching the
            # comparator arm would be read as a bound it never stated.
            arms.append(
                "    when {0} then cast(null as varchar)".format(_matched(LIMITS, rule))
            )
    return _case(arms, "cast(null as varchar)")


def comparator_lookup(column: str, field: str) -> str:
    """The deployment's comparator table, as a CASE over its rows.

    A table and a join would need a row to exist; rendered as a CASE, a
    deployment whose table is empty covers nothing -- which is exactly what
    the Python route does with no table, so the two agree on the empty case
    rather than one of them failing to compile.

    The comparison is against the whole operator run the grammar captured,
    never a prefix of it: a table carrying only ``<`` does not cover ``<=``,
    and reading it as ``<`` would publish a bound the source never stated --
    right number, right side, wrong strictness, which reads as a correct
    answer.
    """
    # Every rendered value is quote-doubled: a code or an operator text is
    # the deployment's own word and may contain an apostrophe, which would
    # otherwise end the literal and break the compile -- or worse, not.
    escape = ' | replace("\'", "\'\'")'
    row = (
        "when {column} = '{{{{ row['text'] | trim{escape} }}}}'"
        " then '{{{{ row[{field!r}]{escape} }}}}'"
    ).format(column=column, field=field, escape=escape)
    return (
        "{% if var('mfg_trace_comparators') %}case"
        "{% for row in var('mfg_trace_comparators') %}\n    "
        + row
        + "{% endfor %}\n    else cast(null as varchar)\nend"
        "{% else %}cast(null as varchar){% endif %}"
    )


def measurement_expressions() -> Dict[str, str]:
    """The grammar's contribution to one curated measurement row.

    Keys are the contract's own column names. There is deliberately no
    expression here for an uncovered operator: the curated contract declares
    no column for one, so it is re-derived in a test of its own
    (:func:`render_uncovered_comparator_test`) rather than carried.

    These read the extraction CTE's columns and ``op_code`` / ``op_bound``
    from the comparator lookup, which :func:`render_test_measurement` wires.
    """
    arms = []
    for rule in RULES:
        if rule.reads_value:
            # Only a plain number may be read as a measurement. A comparator
            # or a tolerance states a bound, and reading `< 50` as a reading
            # of 50 would put a number in the column that was never taken.
            arms.append(
                "    when {0} then {1}".format(
                    _matched(MEASUREMENT, rule),
                    _double(column_for(MEASUREMENT, rule.id, "value")),
                )
            )
        else:
            arms.append(
                "    when {0} then cast(null as double)".format(
                    _matched(MEASUREMENT, rule)
                )
            )
    value_num = _case(arms, "cast(null as double)")

    decimal = "cast({0} as {{{{ var('mfg_trace_decimal_type') }}}})"
    tolerance_rule = next(rule for rule in RULES if rule.kind == "tolerance")
    comparator_rule = next(rule for rule in RULES if rule.kind == "comparator")
    centre = decimal.format(column_for(LIMITS, tolerance_rule.id, "center"))
    tol = decimal.format(column_for(LIMITS, tolerance_rule.id, "tol"))
    bound_value = _double(column_for(LIMITS, comparator_rule.id, "value"))
    tol_matched = _matched(LIMITS, tolerance_rule)

    def bound(sign: str, side: str) -> str:
        return (
            "case\n"
            "    when {tol_matched}\n"
            "        then cast({centre} {sign} {tol} as double)\n"
            "    when op_code is not null and op_bound = '{side}'\n"
            "        then {value}\n"
            "    else cast(null as double)\n"
            "end"
        ).format(
            tol_matched=tol_matched,
            centre=centre,
            sign=sign,
            tol=tol,
            side=side,
            value=bound_value,
        )

    return {
        "measurement_num": value_num,
        "low_limit_num": bound("-", "low"),
        "high_limit_num": bound("+", "high"),
    }


# The curated contract's own column lists, in the order the documents declare
# them. Held here rather than read out of a contract document: the documents
# live in `examples/`, and library SQL that read an example file would make
# the example load-bearing for the package. They are two independent
# statements that must agree, and the package's companion test is what makes
# them agree -- a model whose columns drift from its contract fails there.
RESULT_COLUMNS: Tuple[str, ...] = (
    "result_id",
    "part_number",
    "part_number_raw",
    "serial_number",
    "serial_number_raw",
    "program_name",
    "status_type",
    "is_terminal",
    "started_at",
    "updated_at",
    "duration_s",
    "system_id",
    "host_name",
    "operator_ref",
    "workspace",
    "attempt_seq",
    "is_latest",
    "is_first",
    "source_system",
    "source_record_id",
    "extracted_at",
    "loaded_at",
)

#: The columns of one attempt that a measurement row repeats, as
#: (result column, measurement column). A measurement names the unit under
#: test, so a reader can filter without joining back.
RESULT_COLUMNS_ON_MEASUREMENT: Tuple[Tuple[str, str], ...] = (
    ("started_at", "started_at"),
    ("part_number", "part_number"),
    ("serial_number", "serial_number"),
    ("program_name", "program_name"),
    ("is_latest", "is_latest_result"),
)

#: What the attempt order is computed within: one unit of one part running
#: one program. Written down once because two expressions partition by it.
ATTEMPT_PARTITION: Tuple[str, ...] = ("part_number", "serial_number", "program_name")

#: The catalog's grain, less the unit, which needs an expression of its own.
CATALOG_GRAIN: Tuple[str, ...] = (
    "part_number",
    "program_name",
    "step_path",
    "parameter_name",
)


def _select_list(columns, indent: str = "    ") -> str:
    return "\n".join("{0}{1},".format(indent, column) for column in columns)


def render_test_result() -> str:
    """One row per attempt, with the attempt order and what is latest on it."""
    partition = ", ".join(ATTEMPT_PARTITION)
    body = [
        "with conformed as (",
        "    select * from {{ var('mfg_trace_conf_result_relation') }}",
        "),",
        "",
        "-- The attempt order. Deterministic, including the tie-break: an",
        "-- order that can flip between runs gives a reader a different",
        "-- `attempt_seq` for the same attempt every time the model is built.",
        "attempts as (",
        "    select",
        "        conformed.*,",
        "        row_number() over (",
        "            partition by {0}".format(partition),
        "            order by started_at asc, result_id asc",
        "        ) as attempt_seq",
        "    from conformed",
        "),",
        "",
        "-- The newest attempt that actually REACHED a terminal state, which",
        "-- is what `is_latest` is defined against. The simplification to",
        "-- `attempt_seq = max(attempt_seq)` marks an in-flight run as the",
        "-- latest, so a reader filtering to one row per unit gets a row whose",
        "-- result is not in yet -- which reads as a correct answer.",
        "terminal as (",
        "    select",
        "        attempts.*,",
        "        max(case when is_terminal then attempt_seq end) over (",
        "            partition by {0}".format(partition),
        "        ) as latest_terminal_seq",
        "    from attempts",
        ")",
        "",
        "select",
    ]
    for column in RESULT_COLUMNS:
        if column == "is_latest":
            body.append(
                "    coalesce("
                "is_terminal and (attempt_seq = latest_terminal_seq), false"
                ") as is_latest,"
            )
        elif column == "is_first":
            body.append("    (attempt_seq = 1) as is_first,")
        else:
            body.append("    {0},".format(column))
    body[-1] = body[-1].rstrip(",")
    body.append("from terminal")
    return GENERATED_HEADER + "\n" + "\n".join(body) + "\n"


def render_test_measurement(extract: ExtractRenderer = macro_extract) -> str:
    """One row per measured parameter, with the grammar applied to its text."""
    expressions = measurement_expressions()
    repeated = ",\n".join(
        "        attempt.{0} as attempt_{1}".format(source, target)
        for source, target in RESULT_COLUMNS_ON_MEASUREMENT
    )
    body = [
        "with step_parameter as (",
        "    select * from {{ var('mfg_trace_conf_step_parameter_relation') }}",
        "),",
        "",
        "attempt as (",
        "    select",
        "        result_id,",
        _select_list(
            (source for source, _ in RESULT_COLUMNS_ON_MEASUREMENT),
            indent="        ",
        ).rstrip(","),
        "    from {{ ref('test_result') }}",
        "),",
        "",
        "-- An inner join: a measurement whose attempt is not in the result",
        "-- model has no unit, no program and no `is_latest_result`, and every",
        "-- one of those is a required column here. Carrying the row with",
        "-- nulls would publish a measurement nobody can attribute.",
        "joined as (",
        "    select",
        "        step_parameter.*,",
        repeated,
        "    from step_parameter",
        "    inner join attempt on attempt.result_id = step_parameter.result_id",
        "),",
        "",
        "-- Each pattern applied once, so the expressions below read columns.",
        "extracted as (",
        "    select",
        "        joined.*,",
        extraction_select(extract),
        "    from joined",
        "),",
        "",
        "-- The operator a limits text states, if the text states one at all.",
        "stated as (",
        "    select",
        "        extracted.*,",
        "        {0} as op_text".format(
            indent_block(operator_expression(), "        ")
        ),
        "    from extracted",
        "),",
        "",
        "-- The deployment's comparator table is the only thing that says what",
        "-- an operator MEANS and which side it bounds. This library ships no",
        "-- rows for it, so a deployment that declares none covers none.",
        "coded as (",
        "    select",
        "        stated.*,",
        "        {0} as op_code,".format(
            indent_block(comparator_lookup("op_text", "code"), "        ")
        ),
        "        {0} as op_bound".format(
            indent_block(comparator_lookup("op_text", "bound"), "        ")
        ),
        "    from stated",
        "),",
        "",
        "parsed as (",
        "    select",
        "        coded.*,",
        "        {0} as parsed_measurement_num,".format(
            indent_block(expressions["measurement_num"], "        ")
        ),
        "        {0} as parsed_low_limit_num,".format(
            indent_block(expressions["low_limit_num"], "        ")
        ),
        "        {0} as parsed_high_limit_num,".format(
            indent_block(expressions["high_limit_num"], "        ")
        ),
        "        {0} as parsed_measurement_units,".format(
            indent_block(units_expression(MEASUREMENT), "        ")
        ),
        "        {0} as parsed_limits_units".format(
            indent_block(units_expression(LIMITS), "        ")
        ),
        "    from coded",
        ")",
        "",
        "select",
        "    result_id,",
        "    step_id,",
        "    parameter_index,",
        "    step_path,",
        "    step_name,",
        "    parameter_name,",
        "    parsed_measurement_num as measurement_num,",
        "    measurement_text,",
        "    -- What the source supplied wins; a suffix parsed out of the text",
        "    -- is only a fallback. The other direction silently relabels every",
        "    -- row whose column and suffix disagree.",
        "    coalesce(",
        "        nullif(trim(units), ''),",
        "        parsed_measurement_units,",
        "        parsed_limits_units",
        "    ) as units,",
        "    parsed_low_limit_num as low_limit_num,",
        "    parsed_high_limit_num as high_limit_num,",
        "    limits_text,",
        "    coalesce(nullif(trim(comparison_type), ''), op_code) as comparison_type,",
        "    status,",
        "    -- A measurement that is not a number is only a FAILURE where a",
        "    -- limit is a number: that is what says a number was expected",
        "    -- here. A status word against non-numeric limits parsed fine.",
        "    (",
        "        parsed_measurement_num is null",
        "        and (",
        "            parsed_low_limit_num is not null",
        "            or parsed_high_limit_num is not null",
        "        )",
        "    ) as parse_failed,",
    ]
    for _, target in RESULT_COLUMNS_ON_MEASUREMENT:
        body.append("    attempt_{0} as {0},".format(target))
    body.extend(
        [
            "    source_system,",
            "    source_record_id,",
            "    extracted_at,",
            "    loaded_at",
            "from parsed",
        ]
    )
    return GENERATED_HEADER + "\n" + "\n".join(body) + "\n"


def render_test_catalog() -> str:
    """What has ever been measured, per part and program."""
    grain = _select_list(CATALOG_GRAIN)
    body = [
        "with measurement as (",
        "    select * from {{ ref('test_measurement') }}",
        ")",
        "",
        "select",
        grain,
        "    -- The grain carries the unit, so it cannot be null. The contract",
        "    -- declares how an absent one is written here, and substituting it",
        "    -- is that document's decision rather than this model's. It is",
        "    -- also why the grain stays non-null: a key-uniqueness test over a",
        "    -- nullable column answers whatever the warehouse's null handling",
        "    -- happens to be, which is not a property this package can state.",
        "    coalesce(units, '') as units,",
        "    count(distinct result_id) as n_results,",
        "    min(started_at) as first_seen,",
        "    max(started_at) as last_seen,",
        "    max(loaded_at) as loaded_at",
        "from measurement",
        "group by",
        grain,
        "    coalesce(units, '')",
    ]
    return GENERATED_HEADER + "\n" + "\n".join(body) + "\n"


def render_uncovered_comparator_test(extract: ExtractRenderer = macro_extract) -> str:
    """The rows whose operator the deployment's comparator table misses.

    A singular dbt test, and a **warning** rather than a failure: a table
    short a row is a vocabulary gap to count and close, not a reason to fail
    a build over rows that are otherwise correct -- the limits text is still
    carried verbatim and no wrong bound was published.

    It re-derives the operator from the rule and the table rather than
    reading a published column, because the curated contract declares no
    column for it and a predicate over the published ones cannot tell an
    uncovered operator from a limits text that was never a bound at all.
    """
    body = [
        "{{ config(severity='warn') }}",
        "",
        "with extracted as (",
        "    select",
        "        result_id,",
        "        step_id,",
        "        parameter_index,",
        "        limits_text,",
        extraction_select(extract, sources=(LIMITS,)),
        "    from {{ ref('test_measurement') }}",
        "),",
        "",
        "stated as (",
        "    select",
        "        extracted.*,",
        "        {0} as op_text".format(
            indent_block(operator_expression(), "        ")
        ),
        "    from extracted",
        ")",
        "",
        "select",
        "    result_id,",
        "    step_id,",
        "    parameter_index,",
        "    limits_text,",
        "    op_text",
        "from stated",
        "where op_text is not null",
        "  and {0} is null".format(
            indent_block(comparator_lookup("op_text", "code"), "      ")
        ),
    ]
    return GENERATED_HEADER + "\n" + "\n".join(body) + "\n"


def render_models() -> Dict[str, str]:
    """Every file this module generates, keyed by its path in the package.

    One function so the byte-identity test enumerates nothing of its own: a
    model added here but never shipped fails that test instead of going
    unnoticed.
    """
    files = {
        "models/test_result.sql": render_test_result(),
        "models/test_measurement.sql": render_test_measurement(),
        "models/test_catalog.sql": render_test_catalog(),
        "tests/uncovered_comparator.sql": render_uncovered_comparator_test(),
    }
    for model, grain in GRAINS:
        files["tests/{0}__{1}.sql".format(model, RULE_DUPLICATE_KEY)] = (
            render_duplicate_key_test(model, grain)
        )
    for child, parent, key in ORPHAN_EDGES:
        files["tests/{0}__{1}.sql".format(child, RULE_ORPHAN_REFERENCE)] = (
            render_orphan_reference_test(child, parent, key)
        )
    return files


#: Each curated model's grain, as its contract document declares it. The
#: uniqueness test is derived from this rather than written out per model, so
#: a grain that changes in one place changes the test with it.
#:
#: These are the curated contract's own column names, which are dag-tools'
#: published interface -- not vocabulary from any source system.
GRAINS: Tuple[Tuple[str, Tuple[str, ...]], ...] = (
    ("test_result", ("result_id",)),
    ("test_measurement", ("result_id", "step_id", "parameter_index")),
    (
        "test_catalog",
        ("part_number", "program_name", "step_path", "parameter_name", "units"),
    ),
)

#: Where one curated model's rows must be attributable to another's, as
#: (child model, parent model, key). The measurement model's inner join is
#: what makes this hold, which is exactly why the test is worth shipping: a
#: later edit to an outer join fails here instead of quietly publishing
#: measurements that belong to no attempt.
ORPHAN_EDGES: Tuple[Tuple[str, str, str], ...] = (
    ("test_measurement", "test_result", "result_id"),
)

#: The rule ids these tests fail under. Both are declared by every curated
#: contract document, which is the property that makes a failure actionable:
#: a test naming an id outside the contract's `rules:` cannot be acted on by
#: anyone reading the contract.
RULE_DUPLICATE_KEY = "duplicate_key"
RULE_ORPHAN_REFERENCE = "orphan_reference"


_NL = "\n"


def _rule_header(rule_id: str) -> str:
    return (
        "-- Fails under the contract rule `{rule}`, which this model's" + _NL
        + "-- contract document declares. The id is in this comment and is" + _NL
        + "-- selected as a column, so a failure names the rule wherever" + _NL
        + "-- it is read: a failure naming an id outside the contract's" + _NL
        + "-- `rules:` cannot be acted on by anyone reading the contract." + _NL
    ).format(rule=rule_id)


def render_duplicate_key_test(model: str, grain: Tuple[str, ...]) -> str:
    """Grain uniqueness, as a singular test rather than a generic one.

    Singular because three of these grains are composite, and the built-in
    `unique` test takes one column: the alternative is a dependency on an
    external dbt package for one five-line query, in a library that ships no
    dependency it can avoid. The test's **file name** carries the rule id,
    which is what dbt prints on failure.
    """
    columns = _select_list(grain, indent="        ").rstrip(",")
    body = [
        "with duplicated as (",
        "    select",
        columns + ",",
        "        count(*) as n_rows",
        "    from {{{{ ref('{0}') }}}}".format(model),
        "    group by",
        columns,
        "    having count(*) > 1",
        ")",
        "",
        "select",
        "    '{0}' as rule_id,".format(RULE_DUPLICATE_KEY),
        "    duplicated.*",
        "from duplicated",
    ]
    return (
        GENERATED_HEADER
        + _rule_header(RULE_DUPLICATE_KEY)
        + "\n"
        + "\n".join(body)
        + "\n"
    )


def render_orphan_reference_test(child: str, parent: str, key: str) -> str:
    """A child row whose parent is not in the parent model.

    An anti-join rather than `not_null` on the key: a key that is present
    but names nothing is exactly the orphan the rule is about, and a null
    check passes on it.
    """
    body = [
        "with child as (",
        "    select {0} from {{{{ ref('{1}') }}}}".format(key, child),
        "),",
        "",
        "parent as (",
        "    select {0} from {{{{ ref('{1}') }}}}".format(key, parent),
        ")",
        "",
        "select",
        "    '{0}' as rule_id,".format(RULE_ORPHAN_REFERENCE),
        "    child.{0}".format(key),
        "from child",
        "left join parent on parent.{0} = child.{0}".format(key),
        "where parent.{0} is null".format(key),
    ]
    return (
        GENERATED_HEADER
        + _rule_header(RULE_ORPHAN_REFERENCE)
        + "\n"
        + "\n".join(body)
        + "\n"
    )


#: Where the generated files are shipped. Held here so the regeneration
#: entry point below and the byte-identity test name one path between them:
#: a second spelling of it is how a test ends up comparing the generator
#: against a directory nobody ships.
#:
#: The containing directory is NOT called `dbt_packages`, and that is not a
#: style choice. `dbt_packages/` is where dbt installs the packages a project
#: downloads, so it is in this repo's .gitignore and in every dbt project's --
#: which made every file of this package invisible to git, and therefore
#: absent from the wheel, since the build backend honours VCS ignore files.
#: A shipped package that is missing from the distribution fails at a
#: deployment with a message about a package it cannot find, nowhere near the
#: reason. The name also claims the wrong thing: these are source, not
#: something dbt put here.
PACKAGE_DIR = pathlib.Path(__file__).resolve().parents[1] / "dbt_project_packages" / "mfg_trace_curated"


def write_models(directory: pathlib.Path = PACKAGE_DIR) -> Tuple[str, ...]:
    """Write every generated file, and answer which paths were written.

    UTF-8 and `\n` explicitly, both of which matter: the patterns carry
    `+/-`, micro, ohm, degree and comparison characters, and this repo is
    developed on a platform whose text mode would otherwise write CRLF --
    either of which makes the byte-identity test fail for a reason that has
    nothing to do with the SQL.
    """
    written = []
    for relative, text in sorted(render_models().items()):
        target = directory / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        written.append(relative)
    return tuple(written)


if __name__ == "__main__":  # pragma: no cover - a regeneration entry point
    for path in write_models():
        print(path)
