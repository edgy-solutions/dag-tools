"""A tag gets ONE release, so exactly one workflow may create one.

Two workflows attached a file to each tag's release, and both did it by creating
one. Creating a release for a tag that already has one does not collide -- it
makes a second release -- so `v0.16.0` and `v0.16.1` each carry an empty draft
beside the published release, both created within the same second.

The harm is not the clutter. `generate_release_notes` is set on one of the two
writers, and which of the two releases its notes land on is an accident of
ordering: measured on those tags, `v0.16.0`'s notes went to the draft nobody
sees and its published release has an empty body, while `v0.16.1`'s went to the
published one. A release's body is the one thing on a release that cannot be
reconstructed afterwards from its assets.

So: one creator, and it is the workflow that generates the notes. Every other
writer waits for that release and uploads into it, which is what
`build-containers.yml`'s image record already does and says.

Two properties of this module are deliberate. The assertions are over EVERY
workflow in the repository rather than over the two that exist today, because
the fault arrives with the third writer and a test naming today's files would
pass while it did. And every rule is asserted twice -- once over the shipped
workflows and once over a planted document carrying the defect -- because a
check that has only ever seen the corrected tree says nothing about what it
would do with the broken one.
"""
import pathlib
import re

import pytest

yaml = pytest.importorskip("yaml")

WORKFLOW_DIR = pathlib.Path(__file__).resolve().parents[1] / ".github" / "workflows"
WORKFLOWS = sorted(WORKFLOW_DIR.glob("*.yml"))

#: The action that can CREATE a release. Any version of it.
CREATOR = "softprops/action-gh-release"

#: How a writer that is not the creator adds to a release.
ADDER = "gh release upload"


def _shipped():
    """(name, document) per workflow in the repository."""
    return [
        (path.name, yaml.safe_load(path.read_text(encoding="utf-8"))) for path in WORKFLOWS
    ]


def _steps(fleet):
    for name, document in fleet:
        for job_name, job in (document.get("jobs") or {}).items():
            for step in job.get("steps") or []:
                yield name, job_name, step


def _creators(fleet):
    return [s for s in _steps(fleet) if CREATOR in (s[2].get("uses") or "")]


def _adders(fleet):
    return [s for s in _steps(fleet) if ADDER in (s[2].get("run") or "")]


def _where(found):
    return ["%s / %s / %s" % (f, j, s.get("name")) for f, j, s in found]


# --- the rules, over the shipped workflows ---------------------------------


def test_there_are_workflows_to_check():
    """Anti-vacuity: every rule below is over a glob, and an empty one passes."""
    assert len(WORKFLOWS) >= 2, [p.name for p in WORKFLOWS]


def test_exactly_one_step_in_the_repository_can_create_a_release():
    found = _creators(_shipped())
    assert len(found) == 1, _where(found)


def test_the_creator_is_the_step_that_generates_the_notes():
    """Whichever step creates must be the one with a body to put on it.

    Generated by an ADDER instead, the notes would be written either to a
    release the adder did not make, or to a second one it did.
    """
    (_, _, step), = _creators(_shipped())
    assert step["with"].get("generate_release_notes") is True


def test_no_other_writer_generates_release_notes():
    for name, job, step in _adders(_shipped()):
        run = step["run"]
        assert "generate_release_notes" not in run, "%s / %s" % (name, job)
        assert "--notes" not in run, "%s / %s" % (name, job)


def test_every_other_writer_adds_rather_than_creates():
    """`gh release upload` writes to the release `gh release view` resolves.

    It cannot mint a second one however the race goes, which is the property
    that makes an unordered second writer safe at all.
    """
    adders = _adders(_shipped())
    assert adders, "nothing adds to a release; the chart and the image record both do"
    for name, job, step in adders:
        assert "gh release create" not in step["run"], "%s / %s" % (name, job)


def test_every_other_writer_waits_for_the_release_to_exist():
    """The workflows are not ordered, so an adder may run before the creator.

    Waiting and then failing is the contract: a chart or a record silently
    absent from a release is what a downstream consumer discovers later.
    """
    for name, job, step in _adders(_shipped()):
        run = step["run"]
        where = "%s / %s" % (name, job)
        assert "gh release view" in run, where
        assert "sleep" in run, where
        assert "::error::" in run, where
        assert re.search(r"exit\s+1", run), where


def test_an_adder_uploading_a_GLOB_checks_that_it_matched_something():
    """`fail_on_unmatched_files` is the creator action's; an adder needs its own.

    Unmatched, bash leaves the pattern itself, so the upload is attempted on a
    name that is not a file. This is asked of the adders that upload a glob; an
    adder uploading a file it fetched by name has nothing to come up empty, and
    whether those bytes are the right ones is a question its own job answers.
    One adder must be in scope, or the assertion checked nothing.
    """
    checked = 0
    for name, job, step in _adders(_shipped()):
        run = step["run"]
        where = "%s / %s" % (name, job)
        assert "set -euo pipefail" in run, where
        if "*" not in run:
            continue
        checked += 1
        assert ("[ ! -e " in run) or ("[ ! -f " in run), where
    assert checked, "no adder uploads a glob; this assertion checked nothing"


def test_no_credential_beyond_the_repository_token_is_named():
    """Standing rule: no credential is added to this repository's CI."""
    for path in WORKFLOWS:
        text = path.read_text(encoding="utf-8")
        for secret in re.findall(r"secrets\.([A-Za-z_][A-Za-z0-9_]*)", text):
            assert secret == "GITHUB_TOKEN", "%s names secrets.%s" % (path.name, secret)


# --- the same rules, over the defect ---------------------------------------
# Each of these plants the shape that shipped, or the next one like it. Without
# them, every assertion above is a statement about a tree that is already
# correct.

_A_CREATOR = {
    "name": "Attach to GitHub Release (on tag)",
    "uses": "softprops/action-gh-release@v3",
    "with": {"files": "dist/*.whl", "generate_release_notes": True},
}

_SECOND_CREATOR = {
    "name": "Attach chart to GitHub Release (on tag)",
    "uses": "softprops/action-gh-release@v3",
    "with": {"files": "dist-chart/*.tgz"},
}


def _fleet(*steps):
    return [
        ("planted-%d.yml" % i, {"jobs": {"publish": {"steps": [step]}}})
        for i, step in enumerate(steps)
    ]


def test_control_two_creators_are_found_as_two():
    """The shape that shipped: two workflows, each creating the tag's release."""
    found = _creators(_fleet(_A_CREATOR, _SECOND_CREATOR))
    assert len(found) == 2, _where(found)


def test_control_a_creator_without_notes_is_not_mistaken_for_the_one():
    """And the second one carried no notes, so picking by notes alone is not the rule."""
    (_, _, step), = _creators(_fleet(_SECOND_CREATOR))
    assert step["with"].get("generate_release_notes") is not True


def test_control_an_adder_that_also_creates_is_seen():
    """The tempting fix that is not one: `gh release create` in place of the action.

    It fails for the same reason -- a release for a tag that has one is a second
    release -- and it would satisfy a check that only looked for the action.
    """
    both = {
        "name": "Attach chart",
        "run": (
            'set -euo pipefail\ngh release create "${GITHUB_REF_NAME}" || true\n'
            'gh release upload "${GITHUB_REF_NAME}" dist-chart/*.tgz\n'
        ),
    }
    (_, _, seen), = _adders(_fleet(both))
    assert "gh release create" in seen["run"]


def test_control_an_adder_that_does_not_wait_is_seen():
    """An upload with no wait: green when it runs first, and the asset is absent."""
    step = {
        "name": "Attach chart",
        "run": 'set -euo pipefail\ngh release upload "${GITHUB_REF_NAME}" dist-chart/*.tgz\n',
    }
    (_, _, seen), = _adders(_fleet(step))
    assert "gh release view" not in seen["run"]


def test_control_an_adder_with_an_unchecked_glob_is_seen():
    """A glob that matched nothing, with nothing to say so."""
    step = {
        "name": "Attach chart",
        "run": (
            'set -euo pipefail\nfor _ in $(seq 1 30); do\n'
            '  if gh release view "${GITHUB_REF_NAME}" > /dev/null 2>&1; then\n'
            '    gh release upload "${GITHUB_REF_NAME}" dist-chart/*.tgz --clobber\n'
            '    exit 0\n  fi\n  sleep 10\ndone\n'
            'echo "::error::no release"\nexit 1\n'
        ),
    }
    (_, _, seen), = _adders(_fleet(step))
    assert "*" in seen["run"]
    assert "[ ! -e " not in seen["run"] and "[ ! -f " not in seen["run"]
